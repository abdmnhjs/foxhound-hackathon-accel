import os

# Set this before importing tokenizer-related libraries.
os.environ["TOKENIZERS_PARALLELISM"] = "false"

import json
import math
from datetime import datetime, timezone
from typing import Optional

from dotenv import load_dotenv
from openai import OpenAI
from pydantic import BaseModel, ValidationError
from sentence_transformers import SentenceTransformer
from sklearn.cluster import KMeans


# Load environment variables from ai/.env.
load_dotenv()


# Configuration
EMBEDDING_MODEL_NAME = "paraphrase-multilingual-MiniLM-L12-v2"
GROQ_MODEL = os.getenv("GROQ_MODEL", "openai/gpt-oss-20b")
MAX_FEEDBACKS = 100

GREEN_MAX_SCORE = 33
YELLOW_MAX_SCORE = 66

VOLUME_WEIGHT = 50
ENTITIES_WEIGHT = 30
RECENCY_WEIGHT = 20

RECENCY_HALF_LIFE_DAYS = 30


# Load the embedding model once when this module starts.
# analyze() reuses this object for every request.
embedding_model = SentenceTransformer(EMBEDDING_MODEL_NAME)


def create_groq_client() -> Optional[OpenAI]:
    """Create the Groq client when an API key is configured."""
    api_key = os.getenv("GROQ_API_KEY")

    if not api_key:
        return None

    return OpenAI(
        api_key=api_key,
        base_url="https://api.groq.com/openai/v1",
    )


groq_client = create_groq_client()


class GroupAnalysis(BaseModel):
    """Structured fields generated by the LLM for one cluster."""

    title: str
    summary: str
    contradiction: Optional[str] = None


def parse_iso_date(value: Optional[str]) -> Optional[datetime]:
    """Parse an ISO-8601 timestamp and normalize it to UTC."""
    if not value:
        return None

    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))

        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)

        return parsed.astimezone(timezone.utc)
    except (TypeError, ValueError):
        return None


def choose_cluster_count(feedback_count: int) -> int:
    """Choose roughly one cluster per eight feedbacks, within configured bounds."""
    if feedback_count <= 8:
        return feedback_count

    proposed_count = round(feedback_count / 8)

    return min(
        12,
        feedback_count,
        max(2, proposed_count),
    )


def normalize(value: float, maximum: float) -> float:
    """Normalize a value to the range 0.0–1.0."""
    if maximum <= 0:
        return 0.0

    return min(1.0, value / maximum)


def get_distinct_entity_count(group: list[dict]) -> int:
    """Count distinct users and companies in a group."""
    entities = set()

    for feedback in group:
        user_id = feedback.get("userId")
        company_id = feedback.get("companyId")

        if user_id:
            entities.add(("user", user_id))

        if company_id:
            entities.add(("company", company_id))

    return len(entities)


def calculate_score(
    group: list[dict],
    all_groups: list[list[dict]],
    newest_feedback_date: Optional[datetime],
) -> int:
    """Calculate a transparent priority score from 0 to 100."""
    largest_group_size = max(len(candidate) for candidate in all_groups)
    largest_entity_count = max(
        get_distinct_entity_count(candidate)
        for candidate in all_groups
    )

    volume_component = normalize(
        len(group),
        largest_group_size,
    )

    entity_component = normalize(
        get_distinct_entity_count(group),
        largest_entity_count,
    )

    group_dates = [
        parsed_date
        for feedback in group
        if (
            parsed_date := parse_iso_date(
                feedback.get("createdAt")
            )
        ) is not None
    ]

    if newest_feedback_date is None or not group_dates:
        recency_component = 0.0
    else:
        latest_date_in_group = max(group_dates)
        age_in_days = max(
            0.0,
            (
                newest_feedback_date - latest_date_in_group
            ).total_seconds() / 86400,
        )

        # The recency value is halved for every 30 days of age.
        recency_component = math.pow(
            0.5,
            age_in_days / RECENCY_HALF_LIFE_DAYS,
        )

    score = (
        VOLUME_WEIGHT * volume_component
        + ENTITIES_WEIGHT * entity_component
        + RECENCY_WEIGHT * recency_component
    )

    return max(0, min(100, round(score)))


def priority_from_score(score: int) -> str:
    """Map a numeric score to the agreed priority label."""
    if score < GREEN_MAX_SCORE + 1:
        return "green"

    if score <= YELLOW_MAX_SCORE:
        return "yellow"

    return "red"


def analyze_group_with_llm(group: list[dict]) -> GroupAnalysis:
    """Generate a title, one-sentence summary, and optional contradiction."""
    if groq_client is None:
        raise RuntimeError(
            "GROQ_API_KEY is missing. Add it to ai/.env before running analysis."
        )

    # Send only feedback text to the LLM; IDs and user metadata stay in Python.
    group_texts = [
        feedback["text"]
        for feedback in group
    ]

    request_data = {
        "feedbacks": group_texts,
        "instructions": (
            "Analyze these feedback messages, which have already been grouped "
            "by semantic similarity. Return a short title naming their shared "
            "theme and a one-sentence summary. If the messages express opposing "
            "opinions about the same topic, describe the contradiction in one "
            "sentence. Otherwise return null for contradiction. Do not invent "
            "information that is not present in the feedback."
        ),
    }

    response = groq_client.chat.completions.create(
        model=GROQ_MODEL,
        messages=[
            {
                "role": "system",
                "content": (
                    "You analyze SaaS customer feedback. Return only a JSON "
                    "object with exactly these keys: title, summary, "
                    "contradiction. The summary must be one sentence."
                ),
            },
            {
                "role": "user",
                "content": json.dumps(
                    request_data,
                    ensure_ascii=False,
                ),
            },
        ],
        response_format={"type": "json_object"},
        temperature=0,
    )

    response_text = response.choices[0].message.content

    if not response_text:
        raise ValueError("Groq returned an empty response.")

    try:
        # parse_raw works with the Pydantic versions commonly used by FastAPI.
        return GroupAnalysis.parse_raw(response_text)
    except ValidationError as error:
        raise ValueError(
            f"Groq returned JSON that failed Pydantic validation: {error}"
        ) from error


def analyze(feedbacks: list[dict]) -> dict:
    """
    Cluster prepared feedback, analyze each cluster, calculate its score,
    and return the agreed output structure.
    """
    if not feedbacks:
        return {"groups": []}

    if len(feedbacks) > MAX_FEEDBACKS:
        raise ValueError(
            f"A maximum of {MAX_FEEDBACKS} feedbacks is allowed."
        )

    for feedback in feedbacks:
        if "id" not in feedback or "text" not in feedback:
            raise ValueError(
                "Each feedback must contain both 'id' and 'text'."
            )

    feedback_texts = [
        feedback["text"]
        for feedback in feedbacks
    ]

    if len(feedbacks) == 1:
        # KMeans cannot create two clusters from a single feedback.
        labels = [0]
    else:
        embeddings = embedding_model.encode(
            feedback_texts,
            normalize_embeddings=True,
            show_progress_bar=False,
        )

        cluster_count = choose_cluster_count(len(feedbacks))

        clustering = KMeans(
            n_clusters=cluster_count,
            random_state=0,
            n_init=10,
        )

        labels = clustering.fit_predict(embeddings)

    groups_by_label: dict[int, list[dict]] = {}

    for feedback, label in zip(feedbacks, labels):
        groups_by_label.setdefault(int(label), []).append(feedback)

    # KMeans may produce an unused label, so only observed groups are kept.
    groups = list(groups_by_label.values())

    all_dates = [
        parsed_date
        for feedback in feedbacks
        if (
            parsed_date := parse_iso_date(
                feedback.get("createdAt")
            )
        ) is not None
    ]
    newest_feedback_date = max(all_dates) if all_dates else None

    results = []

    for group in groups:
        generated_analysis = analyze_group_with_llm(group)

        score = calculate_score(
            group=group,
            all_groups=groups,
            newest_feedback_date=newest_feedback_date,
        )

        # IDs come directly from the cluster, so they cannot refer to
        # feedback outside this group.
        feedback_ids = [
            feedback["id"]
            for feedback in group
        ]

        results.append({
            "title": generated_analysis.title,
            "summary": generated_analysis.summary,
            "score": score,
            "priority": priority_from_score(score),
            "contradiction": generated_analysis.contradiction,
            "feedbackIds": feedback_ids,
        })

    results.sort(
        key=lambda group_result: group_result["score"],
        reverse=True,
    )

    return {"groups": results}
